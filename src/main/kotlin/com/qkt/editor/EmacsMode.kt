package com.qkt.editor

import com.qkt.dsl.parse.KeywordCategory

/**
 * Emits `qkt-mode.el`, the Emacs major mode: font-lock from [GrammarVocabulary], the lexer's
 * three comment forms in the syntax table, eglot wired to `qkt lsp`, and a hook that takes a
 * `.qkt` buffer back from `haskell-mode` when a Haskell modeline picked that mode first.
 */
internal object EmacsMode {
    private const val IDENT = "[A-Za-z_][A-Za-z0-9_]*"

    fun render(): String =
        buildString {
            appendLine(";;; qkt-mode.el --- Major mode for qkt strategy files -*- lexical-binding: t -*-")
            appendLine()
            appendLine(";; Generated by `qkt editor grammar --format emacs'; edit src/main/kotlin/com/qkt/editor/")
            appendLine(";; and regenerate rather than editing this file.")
            appendLine(";; Highlighting, comments and indentation for .qkt files, plus completion, hover and live")
            appendLine(";; diagnostics from `qkt lsp' through eglot (built into Emacs 29).")
            appendLine()
            appendLine(";;; Code:")
            appendLine()
            appendLine("(defgroup qkt nil \"qkt strategy files.\" :group 'languages)")
            appendLine()
            appendLine("(defcustom qkt-enable-lsp t")
            appendLine("  \"Start `qkt lsp' through eglot when a .qkt file opens and qkt is on `exec-path'.\"")
            appendLine("  :type 'boolean)")
            appendLine()
            appendLine("(defvar qkt-mode-syntax-table")
            appendLine("  (let ((st (make-syntax-table)))")
            appendLine("    (modify-syntax-entry ?_ \"w\" st)")
            appendLine("    (modify-syntax-entry ?- \". 12b\" st)")
            appendLine("    (modify-syntax-entry ?# \"< b\" st)")
            appendLine("    (modify-syntax-entry ?\\n \"> b\" st)")
            appendLine("    (modify-syntax-entry ?/ \". 14\" st)")
            appendLine("    (modify-syntax-entry ?* \". 23\" st)")
            appendLine("    (modify-syntax-entry ?' \"\\\"\" st)")
            appendLine("    st)")
            appendLine("  \"Syntax table for `qkt-mode': -- and # line comments, /* */ block comments.\")")
            appendLine()
            appendLine("(defconst qkt-font-lock-keywords")
            appendLine("  (list")
            appendLine("   ;; A member after a dot first, so `gold.close' is a field, as the parser reads it.")
            appendLine("   '(\"\\\\.\\\\($IDENT\\\\)\" 1 font-lock-variable-name-face)")
            appendLine("   '(\"\\\\_<\\\\($IDENT\\\\):[A-Za-z0-9_]\" 1 font-lock-type-face)")
            for (category in KeywordCategory.entries) {
                appendLine(
                    "   (cons (regexp-opt '(${quoted(
                        GrammarVocabulary.keywords(category),
                    )}) 'symbols) '${face(category)})",
                )
            }
            val calls = quoted(GrammarVocabulary.indicators + GrammarVocabulary.functions)
            appendLine("   (list (concat (regexp-opt '($calls) 'symbols) \"\\\\s-*(\") 1 'font-lock-builtin-face)")
            appendLine(
                "   (cons (regexp-opt '(${quoted(GrammarVocabulary.constants)}) 'symbols) 'font-lock-constant-face)",
            )
            appendLine("   '(\"\\\\_<\\\\($IDENT\\\\)\\\\s-*(\" 1 font-lock-function-name-face)")
            appendLine(
                "   '(\"\\\\_<[0-9]+\\\\(?:\\\\.[0-9]+\\\\)?\\\\(?:[eE][+-]?[0-9]+\\\\)?[smhd]?\\\\_>\" . font-lock-constant-face))",
            )
            appendLine("  \"Highlighting for `qkt-mode', from the lexer's keyword table and the registries.\")")
            appendLine()
            appendLine("(defvar eglot-server-programs)")
            appendLine("(declare-function eglot-ensure \"eglot\")")
            appendLine()
            appendLine("(with-eval-after-load 'eglot")
            appendLine("  (add-to-list 'eglot-server-programs '(qkt-mode . (\"qkt\" \"lsp\"))))")
            appendLine()
            appendLine(";;;###autoload")
            appendLine("(define-derived-mode qkt-mode prog-mode \"qkt\"")
            appendLine("  \"Major mode for qkt strategy files.\"")
            appendLine("  :syntax-table qkt-mode-syntax-table")
            appendLine("  (setq-local font-lock-defaults '(qkt-font-lock-keywords nil t))")
            appendLine("  (setq-local comment-start \"-- \")")
            appendLine("  (setq-local comment-end \"\")")
            appendLine("  (setq-local comment-start-skip \"\\\\(?:--\\\\|#\\\\)+\\\\s-*\")")
            appendLine("  (setq-local indent-tabs-mode nil)")
            appendLine("  (when (and qkt-enable-lsp (executable-find \"qkt\") (require 'eglot nil t))")
            appendLine("    (eglot-ensure)))")
            appendLine()
            appendLine("(defun qkt--reclaim-from-haskell ()")
            appendLine("  \"Move a .qkt buffer from `haskell-mode' to `qkt-mode'.\"")
            appendLine("  (when (and buffer-file-name (string-match-p \"\\\\.qkt\\\\'\" buffer-file-name))")
            appendLine("    (qkt-mode)))")
            appendLine()
            appendLine(";;;###autoload")
            appendLine("(add-to-list 'auto-mode-alist '(\"\\\\.qkt\\\\'\" . qkt-mode))")
            appendLine("(add-hook 'haskell-mode-hook #'qkt--reclaim-from-haskell)")
            appendLine()
            appendLine("(provide 'qkt-mode)")
            appendLine(";;; qkt-mode.el ends here")
        }

    private fun face(category: KeywordCategory): String =
        when (category) {
            KeywordCategory.SECTION -> "font-lock-preprocessor-face"
            KeywordCategory.STATE, KeywordCategory.AGGREGATE -> "font-lock-builtin-face"
            KeywordCategory.LITERAL -> "font-lock-constant-face"
            else -> "font-lock-keyword-face"
        }

    private fun quoted(names: List<String>): String = names.joinToString(" ") { "\"$it\"" }
}
