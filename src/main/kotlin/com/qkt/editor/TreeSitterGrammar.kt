package com.qkt.editor

import com.qkt.dsl.parse.KeywordCategory

/**
 * Emits the tree-sitter grammar (`grammar.js`) for Zed, Helix and other tree-sitter hosts.
 *
 * The grammar is lexical, like the TextMate one: a file is a flat sequence of keywords (one node
 * type per [KeywordCategory]), calls, member accesses, `BROKER:SYMBOL` references, literals,
 * operators and identifiers. That is all highlighting needs, it never rejects a half-typed file,
 * and the language server owns real parsing. Keywords match case-insensitively, like the lexer,
 * and `word` makes tree-sitter read `.close` as a member rather than the `CLOSE` action.
 */
internal object TreeSitterGrammar {
    /** The node type a keyword of [category] parses as, e.g. `keyword_section`. */
    fun nodeType(category: KeywordCategory): String = "keyword_" + category.name.lowercase()

    fun render(): String =
        buildString {
            appendLine(
                "// tree-sitter grammar for qkt strategy files. Generated by `qkt editor grammar --format tree-sitter`;",
            )
            appendLine("// edit src/main/kotlin/com/qkt/editor/ and regenerate rather than editing this file.")
            appendLine()
            appendLine("// Case-insensitive like the lexer: 'BUY' matches buy, Buy and BUY.")
            appendLine("const ci = (word) =>")
            appendLine(
                "  new RegExp(word.split('').map((c) => (/[a-z]/i.test(c) ? '[' + c.toLowerCase() + c.toUpperCase() + ']' : c)).join(''));",
            )
            appendLine("const words = (...ws) => choice(...ws.map(ci));")
            appendLine()
            appendLine("module.exports = grammar({")
            appendLine("  name: 'qkt',")
            appendLine("  extras: (\$) => [/\\s/, \$.comment],")
            appendLine("  word: (\$) => \$.identifier,")
            appendLine("  rules: {")
            appendLine("    source_file: (\$) => repeat(\$._item),")
            appendLine("    _item: (\$) =>")
            appendLine("      choice(")
            for (category in KeywordCategory.entries) appendLine("        \$.${nodeType(category)},")
            for (rule in listOf("call", "member", "broker_symbol", "duration", "number", "string")) {
                appendLine("        \$.$rule,")
            }
            appendLine("        \$.operator,")
            appendLine("        \$.punctuation,")
            appendLine("        \$.identifier,")
            appendLine("      ),")
            for (category in KeywordCategory.entries) {
                val spellings = GrammarVocabulary.keywords(category).joinToString(", ") { "'$it'" }
                appendLine("    ${nodeType(category)}: (_) => words($spellings),")
            }
            appendLine("    call: (\$) => prec(1, seq(field('name', \$.identifier), '(')),")
            appendLine("    member: (\$) => prec(1, seq('.', field('name', \$.identifier))),")
            appendLine("    broker_symbol: (_) => /[A-Za-z_][A-Za-z0-9_]*:[A-Za-z0-9_][A-Za-z0-9_.\\-]*/,")
            appendLine("    duration: (_) => /\\d+[smhd]/,")
            appendLine("    number: (_) => /\\d+(\\.\\d+)?([eE][+-]?\\d+)?/,")
            appendLine("    string: (_) => choice(/\"([^\"\\\\\\n]|\\\\.)*\"/, /'([^'\\\\\\n]|\\\\.)*'/),")
            appendLine(
                "    comment: (_) => token(choice(seq('--', /.*/), seq('#', /.*/), seq('/*', /[^*]*\\*+([^/*][^*]*\\*+)*/, '/'))),",
            )
            appendLine("    operator: (_) => choice(${OPERATORS.joinToString(", ") { "'$it'" }}),")
            appendLine("    punctuation: (_) => choice(${PUNCTUATION.joinToString(", ") { "'$it'" }}),")
            appendLine("    identifier: (_) => /[A-Za-z_][A-Za-z0-9_]*/,")
            appendLine("  },")
            appendLine("});")
        }

    /** Symbol-form operators, longest first; the same set the TextMate and Vim grammars colour. */
    val OPERATORS = listOf("->", "==", "<>", "!=", "<=", ">=", "<", ">", "=", "+", "-", "*", "/", "%")

    /** Brackets and delimiters. `(` is here for a parenthesis that does not follow a name. */
    val PUNCTUATION = listOf("(", ")", "[", "]", "{", "}", ",", ":", ";", ".", "@", "$")
}
