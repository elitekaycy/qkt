package com.qkt.editor

import com.qkt.dsl.parse.KeywordCategory

/**
 * Emits `highlights.scm` for the [TreeSitterGrammar], once per editor, because Helix and Zed
 * theme different capture names (`constant.numeric` against `number`, and so on). The patterns
 * are the same for both and never overlap, so neither editor's pattern-priority rule matters:
 * a bare identifier is captured only as a direct child of the file, and every name-list
 * pattern pairs with a `#not-match?` twin.
 */
internal object TreeSitterQueries {
    /** An editor's capture-name dialect. */
    enum class Flavor(
        val keyword: (KeywordCategory) -> String,
        val names: Map<String, String>,
    ) {
        HELIX(
            keyword = {
                when (it) {
                    KeywordCategory.SECTION -> "keyword.directive"
                    KeywordCategory.FLOW -> "keyword.control.conditional"
                    KeywordCategory.STATE -> "variable.builtin"
                    KeywordCategory.OPERATOR_WORD -> "keyword.operator"
                    KeywordCategory.AGGREGATE -> "function.builtin"
                    KeywordCategory.LITERAL -> "constant.builtin.boolean"
                    else -> "keyword"
                }
            },
            names =
                mapOf(
                    "builtin" to "function.builtin",
                    "call" to "function",
                    "constant" to "constant.builtin",
                    "field" to "variable.other.member",
                    "broker" to "namespace",
                    "number" to "constant.numeric",
                    "variable" to "variable",
                ),
        ),
        ZED(
            keyword = {
                when (it) {
                    KeywordCategory.STATE -> "variable.special"
                    KeywordCategory.OPERATOR_WORD -> "operator"
                    KeywordCategory.AGGREGATE -> "function"
                    KeywordCategory.LITERAL -> "boolean"
                    else -> "keyword"
                }
            },
            names =
                mapOf(
                    "builtin" to "function",
                    "call" to "function",
                    "constant" to "constant",
                    "field" to "property",
                    "broker" to "type",
                    "number" to "number",
                    "variable" to "variable",
                ),
        ),
    }

    fun render(flavor: Flavor): String =
        buildString {
            val n = flavor.names
            appendLine("; Highlights for qkt (${flavor.name.lowercase()}). Generated by `qkt editor grammar`;")
            appendLine("; edit src/main/kotlin/com/qkt/editor/ and regenerate rather than editing this file.")
            appendLine()
            for (category in KeywordCategory.entries) {
                appendLine("(${TreeSitterGrammar.nodeType(category)}) @${flavor.keyword(category)}")
            }
            appendLine()
            val builtins = names(GrammarVocabulary.indicators + GrammarVocabulary.functions)
            appendLine(
                "((call name: (identifier) @${n.getValue(
                    "builtin",
                )}) (#match? @${n.getValue("builtin")} \"$builtins\"))",
            )
            appendLine(
                "((call name: (identifier) @${n.getValue("call")}) (#not-match? @${n.getValue("call")} \"$builtins\"))",
            )
            appendLine("(member name: (identifier) @${n.getValue("field")})")
            val constants = names(GrammarVocabulary.constants)
            appendLine(
                "((source_file (identifier) @${n.getValue(
                    "constant",
                )}) (#match? @${n.getValue("constant")} \"$constants\"))",
            )
            appendLine(
                "((source_file (identifier) @${n.getValue(
                    "variable",
                )}) (#not-match? @${n.getValue("variable")} \"$constants\"))",
            )
            appendLine("(broker_symbol) @${n.getValue("broker")}")
            appendLine()
            appendLine("(number) @${n.getValue("number")}")
            appendLine("(duration) @${n.getValue("number")}")
            appendLine("(string) @string")
            appendLine("(comment) @comment")
            appendLine("(operator) @operator")
            appendLine("(punctuation) @punctuation")
        }

    /** A case-insensitive whole-name regex over [list], as tree-sitter's Rust regex engine reads it. */
    private fun names(list: List<String>): String = "^(?i)(" + list.joinToString("|") + ")$"
}
